export function tDashboard(locale: Locale, text: string): string {
  if(locale !== "en-US") return text;
  if(Object.prototype.hasOwnProperty.call(translations,text)) return translations[text];
  const overdue = /^(\d+)d atrasado$/.exec(text);
  if(overdue) return overdue[1] + "d overdue";
  const inDays = /^Em (\d+) dias$/.exec(text);
  if(inDays) return "In " + inDays[1] + " days";
  const pct = /^([+-]?[\d,.]+%?) vs\. mês anterior$/.exec(text);
  if(pct) return pct[1] + " vs. previous month";
  return text;
}
